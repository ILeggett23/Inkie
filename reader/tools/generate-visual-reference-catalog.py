#!/usr/bin/env python3
"""Generate identical factual catalogs for the reader and companion; never generates canvas geometry."""
import argparse,json
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--catalog',type=Path,required=True);p.add_argument('--cpp',type=Path,required=True);p.add_argument('--js',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args()
catalog=json.loads(a.catalog.read_text());assert isinstance(catalog,list) and catalog
ids=set()
for ref in catalog:
 assert set(ref)=={'id','aliases','title','url','bindings','matrix','records'} and ref['id'] not in ids
 ids.add(ref['id']);assert ref['url'].startswith('https://') and ref['records']
 assert not any(key in {'points','bounds','canvas','paths','shapes'} for row in ref['records'] for key in row)
raw=json.dumps(catalog,separators=(',',':'),ensure_ascii=True)
cpp='/* Factual records and generic ordinal constraints, never rendering coordinates or templates. Generated by tools/generate-visual-reference-catalog.py. */\nR"facts('+raw+')facts"\n'
js='/* Factual records; no paths, canvas geometry or rendering templates. */\nexport default '+raw+';\n'
for target,text in [(a.cpp,cpp),(a.js,js)]:
 if a.check:assert target.read_text()==text,target
 else:target.write_text(text)
print('VISUAL_REFERENCE_CATALOG_IDENTICAL renderer_geometry=NONE')
